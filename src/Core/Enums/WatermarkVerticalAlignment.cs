namespace FluentUI.Blazor.Community.Components;

/// <summary>
/// Specifies the vertical alignment for a watermark within a container.
/// </summary>
public enum WatermarkVerticalAlignment
{
    /// <summary>
    /// The watermark is aligned to the top of the container.
    /// </summary>
    Top,

    /// <summary>
    /// The watermark is aligned to the middle of the container.
    /// </summary>
    Center,

    /// <summary>
    /// The watermark is aligned to the bottom of the container.
    /// </summary>
    Bottom
}
