namespace FluentUI.Blazor.Community.Components;

/// <summary>
/// Specifies the horizontal alignment for a watermark within a container.
/// </summary>
public enum WatermarkHorizontalAlignment
{
    /// <summary>
    /// The watermark is aligned to the left of the container.
    /// </summary>
    Left,

    /// <summary>
    /// The watermark is aligned to the center of the container.
    /// </summary>
    Center,

    /// <summary>
    /// The watermark is aligned to the right of the container.
    /// </summary>
    Right
}
