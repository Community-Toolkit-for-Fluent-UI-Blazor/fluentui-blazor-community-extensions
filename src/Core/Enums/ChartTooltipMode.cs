namespace FluentUI.Blazor.Community.Components.Enums;

/// <summary>
/// Represents the different modes for displaying tooltips in a charting component.
/// </summary>
public enum ChartTooltipMode
{
    /// <summary>
    /// No tooltip will be displayed.
    /// </summary>
    None,

    /// <summary>
    /// A simple tooltip will be displayed.
    /// </summary>
    Simple,

    /// <summary>
    /// An advanced tooltip will be displayed.
    /// </summary>
    Advanced
}
