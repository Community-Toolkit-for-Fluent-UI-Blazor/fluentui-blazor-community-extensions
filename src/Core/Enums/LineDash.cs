namespace FluentUI.Blazor.Community.Components;

/// <summary>
/// Represents the different styles of line dashes that can be applied to a pen tool.
/// </summary>
public enum LineDash
{
    /// <summary>
    /// Represents a solid line style with no dashes.
    /// </summary>
    Solid,

    /// <summary>
    /// Represents a dash dot dash line style.
    /// </summary>
    DashDot,

    /// <summary>
    /// Represents a dash line style consisting of evenly spaced dashes.
    /// </summary>
    Dashes,

    /// <summary>
    /// Represents a dot line style consisting of evenly spaced dots.
    /// </summary>
    Dots
}
