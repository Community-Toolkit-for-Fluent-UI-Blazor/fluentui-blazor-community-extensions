/// </summary>
public enum ChatMessageReadState
{
    /// <summary>
    /// Represents an unread state.
    /// </summary>
    Unread,

    /// <summary>
    /// Represents a partially read state.
    /// </summary>
    PartiallyRead,

    /// <summary>
    /// Represents a fully read state.
    /// </summary>
    FullyRead
}

