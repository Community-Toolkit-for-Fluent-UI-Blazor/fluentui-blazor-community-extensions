namespace FluentUI.Blazor.Community.Components.Enums;

/// <summary>
/// Specifies the alignment of text content relative to a given point in Scalable Vector Graphics (SVG) rendering.
/// </summary>
/// <remarks>Use this enumeration to control how text is anchored when rendered in SVG elements. The alignment
/// affects how the text is positioned horizontally with respect to the specified coordinate.</remarks>
public enum SvgTextAnchor
{
    /// <summary>
    /// Specifies that content is aligned to the left.
    /// </summary>
    Start,

    /// <summary>
    /// Specifies that content is aligned to the center.
    /// </summary>
    Middle,

    /// <summary>
    /// Specifies that the content is aligned to the right.
    /// </summary>
    End
}
