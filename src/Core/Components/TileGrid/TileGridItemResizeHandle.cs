namespace FluentUI.Blazor.Community.Components;

/// <summary>
/// Specifies the available resize handles for a tile grid item.
/// </summary>
internal enum TileGridItemResizeHandle
{
    /// <summary>
    /// No handle.
    /// </summary>
    None,

    /// <summary>
    /// Represents the bottom resize handle.
    /// </summary>
    Bottom,

    /// <summary>
    /// Represents the right resize handle.
    /// </summary>
    Right,

    /// <summary>
    /// Represents the bottom-right resize handle.
    /// </summary>
    BottomRight
}
