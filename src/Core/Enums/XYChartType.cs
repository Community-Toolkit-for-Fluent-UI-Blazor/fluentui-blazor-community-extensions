namespace FluentUI.Blazor.Community.Components.Enums;

/// <summary>
/// Represents the types of XY charts that can be rendered.
/// </summary>
public enum XYChartType
{
    /// <summary>
    /// Specifies a scatter chart.
    /// </summary>
    Scatter,

    /// <summary>
    /// Specifies a bubble chart.
    /// </summary>
    Bubble,

    /// <summary>
    /// Specifies a line chart.
    /// </summary>
    Line,

    /// <summary>
    /// Specifies an area chart.
    /// </summary>
    Area,

    /// <summary>
    /// Specifies an histogram chart.
    /// </summary>
    Histogram
}
