namespace FluentUI.Blazor.Community.Components.Enums;

/// <summary>
/// Represents the interaction state of a chart item.
/// </summary>
public enum ChartInteractionState
{
    /// <summary>
    /// Represents the normal state of the item.
    /// </summary>
    Normal,

    /// <summary>
    /// Represents the hover state of the item.
    /// </summary>
    Hover,

    /// <summary>
    /// Represents the pressed state of the item.
    /// </summary>
    Pressed,

    /// <summary>
    /// Represents the selected state of the item.
    /// </summary>
    Selected,

    /// <summary>
    /// Represents the disabled state of the item.
    /// </summary>
    Disabled
}
