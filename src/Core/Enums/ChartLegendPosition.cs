namespace FluentUI.Blazor.Community.Components.Enums;

/// <summary>
/// Specifies the possible positions for displaying a chart legend relative to the chart area.
/// </summary>
public enum ChartLegendPosition
{
    /// <summary>
    /// The legend is displayed above the chart area.
    /// </summary>
    Top,

    /// <summary>
    /// The legend is displayed below the chart area.
    /// </summary>
    Bottom,

    /// <summary>
    /// The legend is displayed to the left of the chart area.
    /// </summary>
    Left,

    /// <summary>
    /// The legend is displayed to the right of the chart area.
    /// </summary>
    Right
}
