namespace FluentUI.Blazor.Community.Components.Enums;

/// <summary>
/// Represents the different types of polar charts that can be rendered.
/// </summary>
public enum PolarChartType
{
    /// <summary>
    /// Specifies a radar chart.
    /// </summary>
    Radar,

    /// <summary>
    /// Specifies a polar area chart.
    /// </summary>
    Area,

    /// <summary>
    /// Specifies a polar line chart.
    /// </summary>
    Line,

    /// <summary>
    /// Specifies a polar bar chart.
    /// </summary>
    Bar,

    /// <summary>
    /// Specifies a rose chart.
    /// </summary>
    Rose,

    /// <summary>
    /// Specifies a polar scatter chart.
    /// </summary>
    Scatter,

    /// <summary>
    /// Specifies a polar bubble chart.
    /// </summary>
    Bubble
}
