namespace FluentUI.Blazor.Community.Components.Enums;

/// <summary>
/// Represents the mode of the donut palette used in chart rendering.
/// </summary>
public enum DonutPaletteMode
{
    /// <summary>
    /// The items are grouped by category.
    /// </summary>
    ByCategory,

    /// <summary>
    /// The items are grouped by donut.
    /// </summary>
    ByDonut,

    /// <summary>
    /// The items are grouped by slice.
    /// </summary>
    BySlice
}
