namespace FluentUI.Blazor.Community.Components.Enums;

/// <summary>
/// Represents the shape rendering options for SVG elements.
/// </summary>
public enum SvgShapeRendering
{
    /// <summary>
    /// The ShapeRendering property is not specified.
    /// </summary>
    None,

    /// <summary>
    /// The ShapeRendering property is set to "auto".
    /// </summary>
    Auto,

    /// <summary>
    /// The ShapeRendering property is set to "optimizeSpeed".
    /// </summary>
    OptimizeSpeed,

    /// <summary>
    /// The ShapeRendering property is set to "crispEdges".
    /// </summary>
    CrispEdges,

    /// <summary>
    /// The ShapeRendering property is set to "geometricPrecision".
    /// </summary>
    GeometricPrecision,

    /// <summary>
    /// The ShapeRendering property is set to "optimizeQuality".
    /// </summary>
    OptimizeQuality
}
