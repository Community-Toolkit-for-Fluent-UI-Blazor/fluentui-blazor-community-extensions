namespace FluentUI.Blazor.Community.Components.ColorSpace.Cie;

/// <summary>
/// Represents the standard illuminant names defined by the CIE (Commission Internationale de l'Éclairage).
/// </summary>
public enum IlluminantName
{
    /// <summary>
    /// Represents the light from a tungsten filament of a domestic lamp.
    /// </summary>
    A,

    /// <summary>
    /// Represents the light from the sun at its zenith.
    /// </summary>
    /// <remarks>Correlated color temperature of 4,874 K.</remarks>
    B,

    /// <summary>
    /// Represents the average daylight.
    /// </summary>
    /// <remarks>Correlated color temperature of 6,774 K.</remarks>
    C,

    /// <summary>
    /// Represents the natural daylight at 5,000 K.
    /// </summary>
    D50,

    /// <summary>
    /// Represents the natural daylight at 5,500 K.
    /// </summary>
    D55,

    /// <summary>
    /// Represents the natural daylight at 6,500 K.
    /// </summary>
    D65,

    /// <summary>
    /// Represents the natural daylight at 7,500 K.
    /// </summary>
    D75,

    /// <summary>
    /// Represents an illuminant that gives equal weight to each wavelength of the visible spectrum.
    /// </summary>
    E,

    /// <summary>
    /// Represents a fluorescent light of type 1.
    /// </summary>
    F1,

    /// <summary>
    /// Represents a fluorescent light of type 2.
    /// </summary>
    F2,

    /// <summary>
    /// Represents a fluorescent light of type 3.
    /// </summary>
    F3,

    /// <summary>
    /// Represents a fluorescent light of type 4.
    /// </summary>
    F4,

    /// <summary>
    /// Represents a fluorescent light of type 5.
    /// </summary>
    F5,

    /// <summary>
    /// Represents a fluorescent light of type 6.
    /// </summary>
    F6,

    /// <summary>
    /// Represents a fluorescent light of type 7.
    /// </summary>
    F7,

    /// <summary>
    /// Represents a fluorescent light of type 8.
    /// </summary>
    F8,

    /// <summary>
    /// Represents a fluorescent light of type 9.
    /// </summary>
    F9,

    /// <summary>
    /// Represents a fluorescent light of type 10.
    /// </summary>
    F10,

    /// <summary>
    /// Represents a fluorescent light of type 11.
    /// </summary>
    F11,

    /// <summary>
    /// Represents a fluorescent light of type 12.
    /// </summary>
    F12
}
