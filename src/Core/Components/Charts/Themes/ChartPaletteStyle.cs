namespace FluentUI.Blazor.Community.Components.Charts.Themes;

/// <summary>
/// Specifies the available color palette styles for chart components.
/// </summary>
/// <remarks>Use this enumeration to select a predefined or custom color palette for rendering charts. Some
/// palette styles are designed to improve accessibility for users with color vision deficiencies.</remarks>
public enum ChartPaletteStyle
{
    /// <summary>
    /// Represents the default palette style.
    /// </summary>
    Default,

    /// <summary>
    /// Represents the Neon palette style.
    /// </summary>
    Neon,

    /// <summary>
    /// Represents a pastel palette style.
    /// </summary>
    Pastel,

    /// <summary>
    /// Represents a power bi style.
    /// </summary>
    PowerBi,

    /// <summary>
    /// Represents the Protanopia palette style.
    /// </summary>
    Protanopia,

    /// <summary>
    /// Represents the Deuteranopia palette style.
    /// </summary>
    Deuteranopia,

    /// <summary>
    /// Represents the Tritanopia palette style.
    /// </summary>
    Tritanopia,

    /// <summary>
    /// Represents the Achroma palette style.
    /// </summary>
    Achroma,

    /// <summary>
    /// Represents the Monochrome palette style.
    /// </summary>
    Monochrome,

    /// <summary>
    /// Represents the High Contrast palette style.
    /// </summary>
    HighContrast,

    /// <summary>
    /// Represents the Autumn palette style.
    /// </summary>
    Autumn,

    /// <summary>
    /// Represents the Winter palette style.
    /// </summary>
    Winter,

    /// <summary>
    /// Represents the Spring palette style.
    /// </summary>
    Spring,

    /// <summary>
    /// Represents the Summer palette style.
    /// </summary>
    Summer
}
